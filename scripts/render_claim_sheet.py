"""Render the AUD-01 plain-English claim sheet from a real pack build (P1.7c).

The claim sheet is generated by the existing honest-report generator inside
``ops/audit-pack/pack.py`` (GOV-01 pattern, mandatory no-claim guard intact).
There is no second claim-sheet code path: this CLI builds a real pack in a
temporary directory with the same arguments the pack CLI takes (minus the
output directory), then prints the generated ``claims.md`` it produced.

    python scripts/render_claim_sheet.py \\
      --evidence-store services/investigation-ui/demo_data/evidence_store.jsonl \\
      --trust-roots services/investigation-ui/demo_data/trust_roots.jsonl \\
      --from 2026-11-01 --to 2026-12-01

The rendered sheet is self-guarded: the mandatory no-claim guard header and
sentinel must both be present or the command refuses to print anything.

Nothing leaves the machine; the temporary pack is deleted on exit.
"""

from __future__ import annotations

import importlib.util
import pathlib
import sys
import tempfile

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

_spec = importlib.util.spec_from_file_location(
    "oaa_audit_pack", REPO_ROOT / "ops" / "audit-pack" / "pack.py"
)
assert _spec is not None and _spec.loader is not None
pack = importlib.util.module_from_spec(_spec)
sys.modules["oaa_audit_pack"] = pack
_spec.loader.exec_module(pack)


def main(argv: list[str] | None = None) -> int:
    import argparse

    ap = argparse.ArgumentParser(
        description="Render the claim sheet of a real AUD-01 pack build (P1.7c)"
    )
    ap.add_argument("--evidence-store", required=True, help="evidence store JSONL")
    ap.add_argument("--trust-roots", required=True, help="trust-root snapshot JSONL")
    ap.add_argument("--from", dest="from_s", help="window start, ISO-8601 (UTC assumed)")
    ap.add_argument("--to", dest="to_s", help="window end, ISO-8601 (UTC assumed)")
    ap.add_argument("--receipt-hash", help="optional single receipt (overrides window)")
    ap.add_argument("--policies-dir", help="optional policy directory (yaml/json)")
    ap.add_argument("--policy-receipts", help="optional JSONL of deployment-chain receipt ids")
    ap.add_argument("--clock", help="pinned clock, ISO-8601 (deterministic render)")
    args = ap.parse_args(argv)

    def _utc(s: str | None):
        if s is None:
            return None
        d = pack._parse_utc(s) if hasattr(pack, "_parse_utc") else None
        if d is None:  # pragma: no cover - defensive
            import datetime as dt
            d = dt.datetime.fromisoformat(s)
            d = d.replace(tzinfo=dt.UTC) if d.tzinfo is None else d.astimezone(dt.UTC)
        return d

    policy_lines = (
        pathlib.Path(args.policy_receipts).read_text().splitlines()
        if args.policy_receipts
        else None
    )
    with tempfile.TemporaryDirectory(prefix="oaa-claims-") as td:
        summary = pack.build_pack(
            pathlib.Path(args.evidence_store),
            pathlib.Path(args.trust_roots),
            pathlib.Path(td),
            from_utc=_utc(args.from_s),
            to_utc=_utc(args.to_s),
            receipt_hash=args.receipt_hash,
            policies_dir=pathlib.Path(args.policies_dir) if args.policies_dir else None,
            policy_receipt_hashes=policy_lines,
            clock=_utc(args.clock),
        )
        text = (pathlib.Path(summary["pack_dir"]) / "claims.md").read_text(encoding="utf-8")

    if pack.GUARD_HEADER not in text or pack.GUARD_SENTINEL not in text:
        print(
            "ERROR: generated claim sheet is missing the mandatory no-claim "
            "guard; refusing to render. This is a generator defect, not a "
            "pack property.",
            file=sys.stderr,
        )
        return 1
    pack.assert_no_compliance_claims(text)  # never emit a claim
    print(text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
